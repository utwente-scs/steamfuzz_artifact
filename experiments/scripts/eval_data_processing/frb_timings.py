def parse_hoedur_frb_log(frb_log_path):
    """
    Parse a hoedur *.frb.log to extract which input IDs triggered/reached bugs.

    The log contains lines like:
        HH:MM:SS INFO    hoedur::coverage - Running input N ...
    followed (optionally) by FirmReBugger TRIGGERED/REACHED lines before the
    next "Running input" header.

    Returns {input_id (int): {'reached': set, 'triggered': set}}.
    Only entries with at least one event are included.
    """
    events_by_input = {}
    current_id = None
    current = {'reached': set(), 'triggered': set()}

    with open(frb_log_path) as fh:
        for raw in fh:
            line = raw.rstrip('\n')
            m = _HOEDUR_INPUT_RE.search(line)
            if m:
                # Flush previous section if it had any events.
                if current_id is not None and (current['reached'] or current['triggered']):
                    events_by_input[current_id] = current
                current_id = int(m.group(1))
                current = {'reached': set(), 'triggered': set()}
                continue
            m = _REACHED_RE.match(line.strip())
            if m and current_id is not None:
                current['reached'].add(m.group(1).strip())
                continue
            m = _TRIGGERED_RE.match(line.strip())
            if m and current_id is not None:
                current['triggered'].add(m.group(1).strip())

    # Flush final section.
    if current_id is not None and (current['reached'] or current['triggered']):
        events_by_input[current_id] = current

    return events_by_input


def _read_corpus_input_mtimes(corpus_path):
    """
    Extract mtime (Unix integer) for each ``input/input-N.bin`` entry inside
    a ``*.corpus.tar.zst`` archive (zstd-compressed tar).

    Returns {input_id (int): mtime (int)}.
    """
    id_to_mtime = {}
    dctx = zstandard.ZstdDecompressor()
    with open(corpus_path, 'rb') as fh:
        with dctx.stream_reader(fh) as reader:
            with tarfile.open(fileobj=reader, mode='r|') as tf:
                for member in tf:
                    name = member.name
                    # Match pattern: <folder>/input-<id>.bin
                    parts = name.split('/')
                    if len(parts) == 2 and parts[1].startswith('input-') and parts[1].endswith('.bin'):
                        try:
                            input_id = int(parts[1][len('input-'):-len('.bin')])
                            id_to_mtime[input_id] = int(member.mtime)
                        except ValueError:
                            pass
    return id_to_mtime


def get_hoedur_first_event_times(frb_log_path, corpus_path, event='triggered'):
    """
    Compute first-trigger (or first-reach) times from a hoedur FRB replay.

    elapsed_seconds is measured from the creation time of the very first corpus
    input (``input-1.bin``) to the creation time of the triggering input, using
    the mtime stored in the corpus archive.

    Returns {bug_id: elapsed_seconds (int)}.
    """
    events_by_input = parse_hoedur_frb_log(frb_log_path)
    if not events_by_input:
        return {}

    id_to_mtime = _read_corpus_input_mtimes(corpus_path)
    if not id_to_mtime:
        return {}

    start_time = id_to_mtime[min(id_to_mtime)]

    first_times = {}
    for input_id, section in events_by_input.items():
        mtime = id_to_mtime.get(input_id)
        if mtime is None:
            print(f"Warning: input ID {input_id} found in FRB log but not in corpus archive")
            continue
        elapsed = mtime - start_time
        for bug_id in section.get(event, set()):
            if bug_id not in first_times or elapsed < first_times[bug_id]:
                first_times[bug_id] = elapsed

    return first_times


def collect_hoedur_run_timings(experiment, basedir, fuzzer, event='triggered'):
    """
    Collect first-trigger times for all runs of *fuzzer* in *experiment*.

    Parameters
    ----------
    experiment : dict
        Entry from EXPERIMENTS (must include 'name', 'runs', 'target', 'duration').
    basedir : Path
        Root experiments directory (BASEDIR from config).
    fuzzer : str
        Fuzzer key, e.g. ``'hoedur_steamfuzz'``.
    event : str
        ``'triggered'`` or ``'reached'``.

    Returns
    -------
    dict: {target: {bug_id: [time_or_None, ...]}}
        One element per run (indexed 0..runs-1). None = bug not found that run.
    """
    name = experiment['name']
    runs = experiment['runs']
    duration = experiment.get('duration', '')
    targets = experiment.get('target', [])

    exp_base = experiment.get('path', basedir / name)
    corpus_dir = exp_base / "results" / "fuzzing-runs" / fuzzer / f"{name}-{fuzzer}"

    result = {}
    for target in targets:
        if not (basedir / "targets" / "arm" / target / "bug_descriptor.c").exists():
            print(f"Warning: Skipping target {target} for Hoedur timings because no bug_descriptor.c found")
            continue
        target_dashed = target.replace('/', '-')
        target_bugs = {}

        for run_id in range(1, runs + 1):
            base_filename = (
                f'TARGET-{target_dashed}'
                f'-FUZZER-{fuzzer}'
                f'-RUN-{run_id:02d}'
                f'-DURATION-{duration}'
                f'-MODE-fuzzware'
            )
            frb_log = corpus_dir / f'{base_filename}.frb.log'
            corpus_archive = corpus_dir / f'{base_filename}.corpus.tar.zst'

            if not frb_log.exists() or not corpus_archive.exists():
                print(f"Warning: Missing FRB log or corpus archive for run {run_id} of target {target} ({frb_log}, {corpus_archive})")
                continue

            try:
                timings = get_hoedur_first_event_times(frb_log, corpus_archive, event)
            except Exception as e:
                print(f"Warning: Skipping run {run_id} of target {target} (corrupt frb.log/corpus archive?): {e}")
                continue
            for bug_id, elapsed in timings.items():
                if bug_id not in target_bugs:
                    target_bugs[bug_id] = [None] * runs
                target_bugs[bug_id][run_id - 1] = elapsed

        result[target] = target_bugs

    return result
