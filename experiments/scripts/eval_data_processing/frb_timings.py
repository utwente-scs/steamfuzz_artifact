#!/usr/bin/env python3
"""
Parse aidfuzzer frb.log + frb_plot.log to map input positions to timestamps
and extract per-bug first trigger/reach times for survivability analysis.

frb.log layout
--------------
iofuzz (run mode with FIRMREBUGGER_CONFIG set) writes combined stdout+stderr per
corpus input.  Each input's section ends with the line:

    "  BBs executed: N  IRQs injected: M  MMIO reads: P"

added by the aidfuzzer.patch.  Within a section, FirmReBugger prints:

    "REACHED: <bug_id>"
    "TRIGGERED: <bug_id>"

FirmReBugger deduplicates: within a single QEMU process lifetime the same bug is
only reported once.  If QEMU persists across inputs (snapshot-based), "TRIGGERED"
therefore appears exactly once per bug (for the first triggering input).  Either
way, searching for the first section that contains "TRIGGERED: <bug_id>" gives the
correct first-trigger position.

frb_plot.log layout
-------------------
Generated by passing "-plot frb_plot.log" to iofuzz run (added to
aidfuzzer-run_frb.py).  One line per corpus input, in the SAME order as frb.log:

    "<unix_timestamp> <cumulative_bb_count>"

where unix_timestamp == q->create_time, i.e. the Unix second at which the input
was first added to the corpus during the original fuzzing run.  This is the same
value written to plot.log during coverage collection, but generated here for the
FRB replay specifically so the ordering is guaranteed identical.

Fallback: if frb_plot.log does not exist the code falls back to plot.log (same
format, same order assuming identical corpus contents).
"""

import io
import re
import tarfile
from pathlib import Path
from typing import Optional

import zstandard

# Matches the "BBs executed" line printed by the patched iofuzz per input.
# Handles both regular inputs and crash inputs ("[crash] BBs executed: ...").
_BBs_RE = re.compile(r'^\s+(?:\[crash\]\s+)?BBs executed:\s+\d+')
# Strict versions (start-of-line) used for hoedur logs where the format is clean.
_REACHED_RE = re.compile(r'^REACHED:\s+(.+)$')
_TRIGGERED_RE = re.compile(r'^TRIGGERED:\s+(.+)$')
# Lenient versions (search anywhere in line) used for aidfuzzer logs where
# FirmReBugger output can be mixed into the middle of a line.
_REACHED_ANYWHERE_RE = re.compile(r'REACHED:\s+(\S+)')
_TRIGGERED_ANYWHERE_RE = re.compile(r'TRIGGERED:\s+(\S+)')

# Matches "Running input N ..." lines in hoedur coverage/FRB logs.
_HOEDUR_INPUT_RE = re.compile(r'\bhoedur::(?:coverage|runner) - Running input (\d+)\b')


def parse_frb_sections(frb_log_path):
    """
    Split frb.log into per-input sections.

    Returns a list of dicts, one per corpus input in processing order:
        [{'reached': set(), 'triggered': set()}, ...]

    All lines between (exclusive) consecutive "BBs executed:" delimiters
    are attributed to the same input.
    """
    sections = []
    current = {'reached': set(), 'triggered': set()}
    with open(frb_log_path) as fh:
        for raw in fh:
            line = raw.rstrip('\n')
            m = _REACHED_ANYWHERE_RE.search(line)
            if m:
                current['reached'].add(m.group(1).strip())
                continue
            m = _TRIGGERED_ANYWHERE_RE.search(line)
            if m:
                current['triggered'].add(m.group(1).strip())
                continue
            if _BBs_RE.match(line):
                # "BBs executed:" marks the end of the current input's section.
                sections.append(current)
                current = {'reached': set(), 'triggered': set()}
    # Trailing content without a closing "BBs executed:" line (unusual but safe).
    if current['reached'] or current['triggered']:
        sections.append(current)
    return sections


def parse_plot_log(plot_log_path):
    """
    Parse frb_plot.log or plot.log.

    Returns a list of (create_time_unix, cumulative_bbs) in processing order,
    one entry per corpus input.
    """
    entries = []
    with open(plot_log_path) as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            try:
                ts, bbs = int(parts[0]), int(parts[1])
                entries.append((ts, bbs))
            except ValueError:
                continue
    return entries


def get_first_event_times(frb_log_path, plot_log_path, event='triggered'):
    """
    Return {bug_id: elapsed_seconds} for the first input that triggered or
    reached each bug.

    elapsed_seconds is the number of seconds between the creation of the first
    corpus input (seed, at fuzzing start) and the creation of the triggering
    input, taken directly from q->create_time values in frb_plot.log.

    Parameters
    ----------
    frb_log_path : path-like
    plot_log_path : path-like
        Path to frb_plot.log (preferred) or plot.log (fallback).
    event : str
        'triggered' or 'reached'.

    Returns
    -------
    dict mapping bug_id -> elapsed seconds (int), or empty dict on error.
    """
    sections = parse_frb_sections(frb_log_path)
    plot_entries = parse_plot_log(plot_log_path)

    if not plot_entries:
        return {}

    # The first create_time is the seed input; treat it as time 0.
    start_time = 0

    first_times = {}
    for idx, section in enumerate(sections):
        if idx >= len(plot_entries):
            break
        create_time = plot_entries[idx][0]
        elapsed = create_time - start_time
        for bug_id in section.get(event, set()):
            if bug_id not in first_times:
                first_times[bug_id] = elapsed

    return first_times


# ---------------------------------------------------------------------------
# Convenience helpers for collecting data across all runs of an experiment
# ---------------------------------------------------------------------------

def _find_plot_log(run_dir: Path) -> Optional[Path]:
    """Return frb_plot.log if it exists, else fall back to plot.log."""
    for name in ('frb_plot.log', 'plot.log'):
        p = run_dir / name
        if p.exists():
            return p
    return None


def collect_aidfuzzer_run_timings(experiment, basedir, event='triggered'):
    """
    Collect first-trigger (or first-reach) times for all aidfuzzer runs in *experiment*.

    Parameters
    ----------
    experiment : dict
        An entry from EXPERIMENTS (must include 'name', 'runs', 'target').
    basedir : Path
        Root experiments directory (BASEDIR from config).
    event : str
        'triggered' or 'reached'.

    Returns
    -------
    dict: {target: {bug_id: [time_or_None, ...]}}
        The list has one element per run (indexed 0..runs-1).
        None means the bug was not found in that run.
    """
    name = experiment['name']
    runs = experiment['runs']
    targets = experiment.get('target', [])

    exp_base = experiment.get('path', basedir / name)
    corpus_base = exp_base / "results" / "fuzzing-runs" / "aidfuzzer" / f"{name}-aidfuzzer"

    result = {}
    for target in targets:
        if not (basedir / "targets" / "arm" / target / "bug_descriptor.c").exists():
            continue
        target_bugs = {}
        for run_id in range(1, runs + 1):
            run_dir = corpus_base / f"{target}_{run_id:02d}"
            frb_log = run_dir / "frb.log"
            plot_log = _find_plot_log(run_dir)

            if not frb_log.exists() or plot_log is None:
                # FRB not yet run, or coverage not collected — skip this run.
                continue

            try:
                timings = get_first_event_times(frb_log, plot_log, event)
            except Exception as e:
                print(f"Warning: Skipping run {run_id} of target {target} (corrupt frb.log/plot.log?): {e}")
                continue
            for bug_id, elapsed in timings.items():
                if bug_id not in target_bugs:
                    target_bugs[bug_id] = [None] * runs
                target_bugs[bug_id][run_id - 1] = elapsed

        result[target] = target_bugs

    return result


